const ALLOW = ["バカンス", "カロリー", "ロリポップ", "エターナル", "エタニティ", "キッチン", "キチン", "シネマ", "ホモジ", "テロップ", "サブスク", "スカル", "エッチング", "裸足", "裸眼", "オーナー", "投資信託", "ちょんまげ", "チョンマゲ", "ハゲタカ", "デブリ", "ボケット"];
const ALLOW_N = ALLOW.map(norm);
const isHira = (w) => /^[ぁ-ん]+$/.test(w);
export function ngCheck(text) {
  const raw = String(text || "").normalize("NFKC");
  if (PII.some((re) => re.test(raw))) return "pii";
  let n = norm(raw);
  for (const a of ALLOW_N) n = n.split(a).join("|");
  const low = raw.toLowerCase();
  for (const w of LIST) {
    // ひらがな2文字以下の言葉（しね など）は、ほかの言葉の一部になりやすいので、単独で書かれたときだけ止める
    if (w.length <= 2 && isHira(w)) { if (n === w || new RegExp(`(^|[^ぁ-んァ-ヶ一-龥a-z])${w}($|[^ぁ-んァ-ヶ一-龥a-z])`).test(low)) return w; }
    else if (n.includes(w)) return w;
  }
  return null;
}

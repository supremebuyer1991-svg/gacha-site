const norm = (s) => String(s || "").normalize("NFKC").toLowerCase().replace(/[\s　・･\-ー_~〜～.。、,!！?？*＊/／]/g, "");
const LIST = [...new Set(WORDS.map((w) => norm(w)).filter(Boolean))];
// 電話番号・メールアドレスらしいもの
const PII = [/0\d{1,4}[-−ー\s]?\d{1,4}[-−ー\s]?\d{3,4}/, /[\w.+-]+＠?@[\w-]+\.[\w.]+/, /\d{3}[-−]?\d{4}[-−]?\d{4}/];
